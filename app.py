from __future__ import annotations

import os
from datetime import date
from pathlib import Path

import pandas as pd
import streamlit as st
from dotenv import load_dotenv

from src.db import database as db
from src.models.schemas import SupplierInput
from src.services import evaluation_service
from src.services.evaluation_service import ConfigurationError, is_demo_mode
from src.services.input_validation import validate_supplier_forms
from src.tools.criteria_validation import CriteriaWeightError, validate_weights_sum_to_100

load_dotenv()

DB_PATH = os.environ.get("DATABASE_PATH", "data/app.db")
db.init_db(DB_PATH)

st.set_page_config(page_title="Agentic RFP Evaluation & Supplier Ranking", layout="wide", page_icon="📋")

st.title("📋 Agentic RFP Evaluation & Supplier Ranking")
st.caption(
    "LLM-assisted evidence extraction, plus fully deterministic validation, scoring, "
    "benchmarking, PPI and ranking — an agentic procurement evaluation workflow."
)

if is_demo_mode():
    st.warning(
        "**DEMO MODE — synthetic evaluation.** Criterion scores are generated by "
        "deterministic keyword heuristics, not a real LLM call. Set `DEMO_MODE=false` "
        "and configure an API key for production evaluations.",
        icon="🧪",
    )

with st.sidebar:
    st.header("Configuration")
    provider_label = "Demo (synthetic)" if is_demo_mode() else os.environ.get("LLM_PROVIDER", "openai")
    st.write(f"**LLM provider:** {provider_label}")
    st.write(f"**Database:** `{DB_PATH}`")
    if st.button("Clear current run"):
        st.session_state.pop("current_run", None)
        st.rerun()

tabs = st.tabs(
    [
        "1. Evaluation Criteria",
        "2. Supplier Input",
        "3. Evaluate",
        "4. Leaderboard",
        "5. Supplier Scorecard",
        "6. Run Details",
    ]
)

# ============================================================== 1. Criteria
with tabs[0]:
    st.subheader("Evaluation Criteria")
    st.caption(
        "Criteria are loaded from SQLite — never hard-coded into the LLM prompt. "
        "Active weights must sum to 100% before an evaluation can run."
    )

    conn = db.get_connection(DB_PATH)
    try:
        all_criteria = db.get_all_criteria(conn)
    finally:
        conn.close()

    criteria_df = pd.DataFrame(
        [
            {
                "criterion_id": c.criterion_id,
                "Name": c.name,
                "Description": c.description,
                "Weight (%)": c.weight,
                "Max Score": c.max_score,
                "Active": c.is_active,
            }
            for c in all_criteria
        ]
    )

    edited = st.data_editor(
        criteria_df,
        column_config={
            "criterion_id": None,
            "Name": st.column_config.TextColumn(disabled=True),
            "Description": st.column_config.TextColumn(disabled=True),
            "Max Score": st.column_config.NumberColumn(disabled=True),
            "Weight (%)": st.column_config.NumberColumn(min_value=0, max_value=100, step=1),
            "Active": st.column_config.CheckboxColumn(),
        },
        hide_index=True,
        num_rows="fixed",
        use_container_width=True,
        key="criteria_editor",
    )

    active_total = edited.loc[edited["Active"], "Weight (%)"].sum()
    if abs(active_total - 100) < 0.01:
        st.success(f"Active criteria weights sum to {active_total:.1f}%. Ready to evaluate.")
    else:
        st.error(f"Active criteria weights sum to {active_total:.1f}%, not 100%. Adjust weights before evaluating.")

    if st.button("Save Criteria Changes"):
        conn = db.get_connection(DB_PATH)
        try:
            for _, row in edited.iterrows():
                db.set_criterion_weight(conn, int(row["criterion_id"]), float(row["Weight (%)"]))
                db.set_criterion_active(conn, int(row["criterion_id"]), bool(row["Active"]))
        finally:
            conn.close()
        st.success("Criteria updated.")
        st.rerun()

# ========================================================== 2. Supplier Input
with tabs[1]:
    st.subheader("Supplier Input")
    st.caption("Upload each supplier's RFP/proposal PDF and provide submission metadata.")

    uploaded_files = st.file_uploader(
        "Upload supplier proposal PDFs",
        type=["pdf"],
        accept_multiple_files=True,
        key="pdf_uploader",
    )

    if uploaded_files:
        for f in uploaded_files:
            default_name = Path(f.name).stem.replace("_", " ").replace("-", " ").title()
            with st.expander(f"📄 {f.name}", expanded=True):
                col1, col2, col3 = st.columns(3)
                col1.text_input("Supplier name", value=default_name, key=f"name_{f.name}")
                col2.date_input("Submission date", value=date.today(), key=f"date_{f.name}")
                col3.number_input(
                    "Historical experience rating (0-10)",
                    min_value=0.0,
                    max_value=10.0,
                    step=0.5,
                    value=5.0,
                    key=f"exp_{f.name}",
                )
    else:
        st.info("Upload one or more supplier PDFs to begin.")

# ================================================================ 3. Evaluate
with tabs[2]:
    st.subheader("Evaluate Suppliers")

    entries = []
    for f in st.session_state.get("pdf_uploader") or []:
        entries.append(
            {
                "supplier_name": (st.session_state.get(f"name_{f.name}") or "").strip(),
                "submission_date": st.session_state.get(f"date_{f.name}"),
                "experience_rating": st.session_state.get(f"exp_{f.name}"),
                "file_bytes": f.getvalue(),
                "file_name": f.name,
            }
        )

    errors = validate_supplier_forms(entries)

    conn = db.get_connection(DB_PATH)
    try:
        active_criteria = db.load_active_criteria(conn)
    finally:
        conn.close()

    try:
        validate_weights_sum_to_100(active_criteria)
    except CriteriaWeightError as exc:
        errors.append(str(exc))

    if errors:
        st.error("Please resolve the following before evaluating:")
        for e in errors:
            st.write(f"- {e}")
    else:
        st.success(f"{len(entries)} supplier(s) ready. All validations passed.")

    run_clicked = st.button(
        "EVALUATE SUPPLIERS",
        type="primary",
        disabled=bool(errors) or not entries,
    )

    if run_clicked:
        supplier_inputs = [
            SupplierInput(
                supplier_name=e["supplier_name"],
                submission_date=e["submission_date"],
                experience_rating=e["experience_rating"],
                file_name=e["file_name"],
                file_bytes=e["file_bytes"],
            )
            for e in entries
        ]

        status_box = st.status("Running agentic evaluation workflow...", expanded=True)

        def on_event(stage, supplier, status, **fields):
            label = stage.replace("_", " ").title()
            who = f" — {supplier}" if supplier else ""
            extra = ", ".join(f"{k}={v}" for k, v in fields.items())
            status_box.write(f"**{label}{who}**: {status}" + (f" ({extra})" if extra else ""))

        try:
            run_result = evaluation_service.run_evaluation(DB_PATH, supplier_inputs, on_event=on_event)
            st.session_state["current_run"] = run_result
            status_box.update(label=f"Evaluation complete — {run_result.rfp_run_id}", state="complete")
            st.success(f"Run {run_result.rfp_run_id} completed. See the Leaderboard tab for results.")
        except ConfigurationError as exc:
            status_box.update(label="Evaluation failed", state="error")
            st.error(
                f"LLM configuration error: {exc}\n\n"
                "Set the required API key in your environment/.env, or set DEMO_MODE=true "
                "to run without one."
            )
        except CriteriaWeightError as exc:
            status_box.update(label="Evaluation failed", state="error")
            st.error(str(exc))

# ============================================================== 4. Leaderboard
with tabs[3]:
    st.subheader("Leaderboard")
    run_result = st.session_state.get("current_run")
    if not run_result:
        st.info("Run an evaluation from the Evaluate tab to see the leaderboard.")
    else:
        st.caption(
            "Ranking is generated entirely from validated, LLM-extracted criterion scores "
            "plus deterministic benchmarking, PPI, and tie-break rules — never an LLM opinion."
        )
        rows = [
            {
                "Rank": s.final_rank if s.final_rank else "—",
                "Supplier": s.supplier_name,
                "Status": s.status,
                "Absolute Score": s.absolute_score,
                "PPI": s.ppi,
                "Submission Date": s.submission_date,
                "Experience Rating": s.experience_rating,
            }
            for s in run_result.suppliers
        ]
        st.dataframe(pd.DataFrame(rows), hide_index=True, use_container_width=True)

        failed = [s for s in run_result.suppliers if s.status != "OK"]
        if failed:
            st.warning(f"{len(failed)} supplier(s) failed evaluation and are excluded from ranking. See Run Details.")

# ======================================================= 5. Supplier Scorecard
with tabs[4]:
    st.subheader("Supplier Scorecard")
    run_result = st.session_state.get("current_run")
    if not run_result:
        st.info("Run an evaluation from the Evaluate tab to see supplier scorecards.")
    else:
        names = [s.supplier_name for s in run_result.suppliers]
        selected = st.selectbox("Select a supplier", names)
        supplier = next(s for s in run_result.suppliers if s.supplier_name == selected)

        if supplier.status != "OK":
            st.error(f"Evaluation failed for {supplier.supplier_name}: {supplier.overall_summary}")
            if supplier.extraction_warning:
                st.caption(f"Extraction warning: {supplier.extraction_warning}")
        else:
            c1, c2, c3, c4, c5 = st.columns(5)
            c1.metric("Final Rank", supplier.final_rank)
            c2.metric("Absolute Score", f"{supplier.absolute_score:.1f} / 100")
            c3.metric("PPI", f"{supplier.ppi:.1f}")
            c4.metric("Submission Date", str(supplier.submission_date))
            c5.metric("Experience Rating", supplier.experience_rating)

            st.caption(supplier.tie_break_notes)

            if supplier.overall_summary:
                st.markdown(f"**Overall summary:** {supplier.overall_summary}")
            if supplier.risks:
                st.markdown("**Identified risks:**")
                for r in supplier.risks:
                    st.write(f"- {r}")

            st.divider()
            st.markdown("### Criterion-Level Detail")
            for cr in supplier.criteria:
                status_flag = " ⚠️" if cr.validation_status != "OK" else ""
                with st.expander(
                    f"{cr.name}{status_flag} — {cr.score}/{cr.max_score}  "
                    f"(Weight: {cr.weight:.0f}%, Benchmark: {cr.benchmark}, "
                    f"Gap: {cr.gap}, Relative: {cr.relative_performance}%)"
                ):
                    st.markdown(f"**Evidence:**\n\n{cr.evidence or '_No evidence provided._'}")
                    st.markdown(f"**Justification:**\n\n{cr.justification or '_No justification provided._'}")

            if supplier.warnings:
                st.divider()
                st.markdown("### Validation Warnings")
                for w in supplier.warnings:
                    st.write(f"- **{w.warning_type}**: {w.message}")

# ============================================================ 6. Run Details
with tabs[5]:
    st.subheader("Run Details")
    run_result = st.session_state.get("current_run")
    if not run_result:
        st.info("Run an evaluation from the Evaluate tab to see run details.")
    else:
        st.write(f"**RFP Run ID:** `{run_result.rfp_run_id}`")
        st.write(f"**Created (UTC):** {run_result.created_at}")
        st.write(f"**Status:** {run_result.status}")
        st.write(f"**Suppliers evaluated:** {len(run_result.suppliers)}")
        st.write(f"**LLM provider / model:** {run_result.llm_provider} / {run_result.llm_model}")
        st.write(f"**Demo mode:** {run_result.demo_mode}")

        st.markdown("### Criteria Used")
        st.dataframe(
            pd.DataFrame([c.model_dump() for c in run_result.criteria]),
            hide_index=True,
            use_container_width=True,
        )

        st.markdown("### Tie-Break Explanations")
        for s in run_result.suppliers:
            st.write(f"- **{s.supplier_name}**: {s.tie_break_notes}")

        all_warnings = [(s.supplier_name, w) for s in run_result.suppliers for w in s.warnings]
        st.markdown(f"### Validation Warnings ({len(all_warnings)})")
        if all_warnings:
            st.dataframe(
                pd.DataFrame([{"Supplier": name, **w.model_dump()} for name, w in all_warnings]),
                hide_index=True,
                use_container_width=True,
            )
        else:
            st.write("No validation warnings were raised in this run.")

        st.divider()
        st.download_button(
            "Download complete run as JSON",
            data=run_result.model_dump_json(indent=2),
            file_name=f"{run_result.rfp_run_id}.json",
            mime="application/json",
        )

        with st.expander("Browse past runs"):
            conn = db.get_connection(DB_PATH)
            try:
                past_runs = db.list_runs(conn)
            finally:
                conn.close()
            if past_runs:
                st.dataframe(pd.DataFrame([dict(r) for r in past_runs]), hide_index=True, use_container_width=True)
            else:
                st.write("No past runs found.")
